type MaterialModalProps = {
  isOpen: boolean;
  onClose: () => void;
  onSave: (saved: RawMaterial) => void;
  material: RawMaterial | null;
  onUpsertAction: (input: UpsertRawMaterialInput) => Promise<RawMaterial>;
};

