import { useState, useMemo } from "react";
import { createPortal } from "react-dom";
import {
  X,
  Sparkles,
  AlertCircle,
  Layers,
  CheckSquare,
  ChevronDown,
  ChevronUp,
  Info,
} from "lucide-react";
import { cn } from "@/lib/utils";
import {
  type RawMaterial,
  type RawMaterialCategory,
  type BillingUnit,
} from "@/lib/pricing/types";
